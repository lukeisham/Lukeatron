def main() -> None:
    if FIXTURE_ROOT.exists():
        shutil.rmtree(FIXTURE_ROOT)
    PROJECTS_DIR.mkdir(parents=True, exist_ok=True)
    MINOR_TASKS_DIR.mkdir(parents=True, exist_ok=True)
    (FIXTURE_ROOT / "Outbox").mkdir(parents=True, exist_ok=True)

    for p in ALL_PROJECTS:
        project_dir = PROJECTS_DIR / p.dir_name
        project_dir.mkdir(parents=True, exist_ok=True)
        (project_dir / "registry.md").write_text(render_registry(p), encoding="utf-8")

    (PROJECTS_DIR / "_tracking.yaml").write_text(render_tracking(ALL_PROJECTS), encoding="utf-8")
    (MINOR_TASKS_DIR / "queue.md").write_text(render_queue(), encoding="utf-8")

    print(f"seed_fixture.py: wrote {len(ALL_PROJECTS)} projects under {PROJECTS_DIR}")
    print(f"seed_fixture.py: wrote {MINOR_TASKS_DIR / 'queue.md'}")
    print(f"seed_fixture.py: LUKEATRON_ROOT for this fixture is {FIXTURE_ROOT}")


if __name__ == "__main__":
    main()
