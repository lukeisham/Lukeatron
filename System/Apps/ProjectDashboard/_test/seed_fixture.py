def render_registry(p: Project) -> str:
    frontmatter = (
        "---\n"
        f'project: "{p.slug}"\n'
        f'id: "{p.id}"\n'
        f'title: "{p.title}"\n'
        f"context: {p.context}\n"
        "status: Active\n"
        "---\n"
    )
    if p.legacy_columns:
        header = "| # | Action | Owner | Status | Due |\n|---|--------|-------|--------|-----|\n"
        lines = [
            f"| {n} | {r.action} | {r.owner} | {r.status} | {r.due} |"
            for n, r in enumerate(p.rows, start=1)
        ]
    else:
        header = (
            "| # | Action | Owner | Kind | Effort | Tokens | Status | State | Due |\n"
            "|---|--------|-------|------|--------|--------|--------|-------|-----|\n"
        )
        lines = [
            f"| {n} | {r.action} | {r.owner} | {r.kind} | {r.effort} | {r.tokens} | "
            f"{r.status} | {r.state} | {r.due} |"
            for n, r in enumerate(p.rows, start=1)
        ]
    return frontmatter + "\n# ✅ Next Actions\n\n" + header + "\n".join(lines) + "\n"


def render_tracking(projects: list[Project]) -> str:
    lines = [
        "# GENERATED by seed_fixture.py — do not hand-edit. Re-run the script instead.",
        "# Obviously-fake TEST fixture: every id, title and date below is invented.",
        "projects:",
    ]
    for p in projects:
        updated = TODAY - timedelta(days=p.updated_days_ago)
        wake = iso(p.wake) if p.wake else ""
        lines += [
            f"  - id: {p.id}",
            f"    project: {p.slug}",
            f'    title: "{p.title}"',
            f"    context: {p.context}",
            "    status: Active",
            '    state: "⚪ undefined"',
            '    waiting_on: ""',
            f'    wake: "{wake}"',
            f"    created: {(TODAY - timedelta(days=200)).isoformat()}",
            f"    updated: {updated.isoformat()}",
            f"    path: {p.rel_registry_path}",
            "",
        ]
    return "\n".join(lines) + "\n"


