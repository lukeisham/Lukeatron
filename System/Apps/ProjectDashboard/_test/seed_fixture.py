@dataclass
class Row:
    action: str
    owner: str = "—"
    kind: str | None = "unshaped"   # None => omit the Kind cell text (legacy)
    effort: str | None = "—"
    tokens: str | None = "—"
    status: str = "☐ Open"
    state: str = "⚪ undefined"
    due: str = "—"


@dataclass
class Project:
    id: str
    title: str
    context: str
    rows: list[Row]
    legacy_columns: bool = False   # FK-08: no Kind/Effort/Tokens columns at all
    updated_days_ago: int = 6
    wake: date | None = None

    @property
    def slug(self) -> str:
        return slugify(self.title)

    @property
    def dir_name(self) -> str:
        return f"{self.id}-{self.slug}"

    @property
    def rel_registry_path(self) -> str:
        return f"Memory/Medium-Term/Projects/{self.dir_name}/registry.md"


