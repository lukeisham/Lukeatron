#!/usr/bin/env python3
"""Bundle the MiniWiki module's ES-module source (src/*.js) into one
non-module script the shell's assembler can inject verbatim.

Mirrors _modules/Spelling/build/bundle_spelling.py exactly (SR-4): the
parser widgets are a single offline HTML file with no module loader, so
this script concatenates src/*.js in dependency order, strips their
`import {...} from "./x.js";` / `export {...};` statements, re-creates any
aliased import as a top-level `var alias = original;`, and wraps the
result in an IIFE assigning one global: `window.createMiniWikiModule`
(spec FR-1).

Usage:
  python3 build/bundle_miniwiki.py [--out dist/miniwiki.bundle.js]

Stdlib only (PY-1/SR-2). Run after any src/*.js edit and before running
_shell/build/assemble.py on a cartridge with miniwiki.enabled: true.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

MODULE_DIR = Path(__file__).resolve().parents[1]
SRC_DIR = MODULE_DIR / "src"
DEFAULT_OUT = MODULE_DIR / "dist" / "miniwiki.bundle.js"

# Dependency order (leaves first) — matches each file's own `import` graph.
# Every entry becomes plain top-level `function` declarations inside one
# IIFE (strip_module_syntax()), so hoisting makes textual order harmless
# even across the ui.js <-> article-nav.js/search-ui.js/popover.js cycle
# below (each only calls the other's functions from inside its own
# function bodies, never at module-evaluation time) — this list is ordered
# leaves-first purely for readability, not because the bundler requires it.
ORDER = [
    "tree.js",
    "autolink.js",
    "search-terms.js",
    "references.js",
    "clipboard.js",
    "markdown.js",
    "styles.js",
    "styles-interactive.js",
    "article-nav.js",
    "search-ui.js",
    "popover.js",
    "nav-active.js",
    "drawer.js",
    "ui.js",
    "index.js",
]

IMPORT_RE = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*[\"'][^\"']+[\"'];\s*$", re.MULTILINE)
EXPORT_RE = re.compile(r"^export\s*\{[^}]*\};\s*$", re.MULTILINE)
ALIAS_RE = re.compile(r"^\s*(\S+)\s+as\s+(\S+)\s*$")


class BundleError(Exception):
    """Raised when a source file doesn't match the expected import/export shape (PY-6)."""


def collect_aliases(text: str) -> list[str]:
    aliases: list[str] = []
    for names in IMPORT_RE.findall(text):
        for entry in names.split(","):
            m = ALIAS_RE.match(entry.strip())
            if m:
                aliases.append(f"var {m.group(2)} = {m.group(1)};")
    return aliases


def strip_module_syntax(text: str, name: str) -> str:
    stripped = IMPORT_RE.sub("", text)
    stripped = EXPORT_RE.sub("", stripped)
    if "import " in stripped or re.search(r"^export\b", stripped, re.MULTILINE):
        raise BundleError(
            f"{name}: import/export syntax survived stripping — bundler regex didn't match "
            f"this file's actual shape; fix the bundler, don't ship broken output"
        )
    return stripped


def bundle() -> str:
    parts: list[str] = [
        "/* AUTO-GENERATED by build/bundle_miniwiki.py — do not edit by hand.\n"
        "   Source of truth is _modules/MiniWiki/src/*.js; rerun the bundler\n"
        "   after any source edit. Concatenated in dependency order, module\n"
        "   syntax stripped, wrapped in one IIFE exposing window.createMiniWikiModule. */",
        "(function (global) {",
        '"use strict";',
    ]
    missing = [name for name in ORDER if not (SRC_DIR / name).exists()]
    if missing:
        raise BundleError(f"expected source file(s) not found in {SRC_DIR}: {missing}")

    aliases: list[str] = []
    for name in ORDER:
        path = SRC_DIR / name
        raw = path.read_text(encoding="utf-8")
        aliases.extend(collect_aliases(raw))
        parts.append(f"\n/* ---- src/{name} ---- */\n")
        parts.append(strip_module_syntax(raw, name))

    if aliases:
        parts.append("\n/* ---- import aliases (flattened from per-file ES-module renames) ---- */\n")
        parts.append("\n".join(aliases))

    parts.append(
        "\nglobal.createMiniWikiModule = createMiniWikiModule;\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n"
    )
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    try:
        output = bundle()
    except BundleError as exc:
        raise SystemExit(f"bundle_miniwiki.py: {exc}") from exc

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")
    print(f"wrote {args.out}: {len(output):,} bytes")


if __name__ == "__main__":
    main()
