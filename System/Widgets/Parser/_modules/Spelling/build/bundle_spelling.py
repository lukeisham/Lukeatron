#!/usr/bin/env python3
"""Bundle the Spelling module's ES-module source (src/*.js) into one
non-module script the shell's assembler can inject verbatim.

The module's source (`_modules/Spelling/src/`) is written as ES modules
(import/export) per its own house style — but the parser widgets are a
single offline HTML file with no build step / bundler / module loader
(HTML-4-ish, and JS-7's "no build step" for the shell itself). This
script is the one place that gap is bridged: concatenate the modules in
dependency order, strip their `import {...} from "./x.js";` and
`export {...};` statements (both always well-formed brace blocks in this
source, verified by inspection), and wrap the result in an IIFE that
assigns exactly two globals: `window.createSpellingModule` (spec FR-1)
and `window.SpellingBackend` (the backend helpers a host needs to open
the embedded dictionary — `createSqlJsBackend`, `supportsGzipDecompression`,
`decompressGzipBase64`, per backend.js's own exports).

Usage:
  python3 build/bundle_spelling.py [--out dist/spelling.bundle.js]

Stdlib only (PY-1/SR-2). Run after any src/*.js edit and before running
_shell/build/assemble.py on a cartridge with spelling.enabled: true — the
assembler embeds this bundle's *current on-disk contents*, it does not
invoke this script itself (SR-1: one script, one job).
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

MODULE_DIR = Path(__file__).resolve().parents[1]
SRC_DIR = MODULE_DIR / "src"
DEFAULT_OUT = MODULE_DIR / "dist" / "spelling.bundle.js"

# Dependency order (leaves first) — matches each file's own `import` graph.
ORDER = [
    "qwerty.js",
    "distance.js",
    "metaphone.js",
    "tokenizer.js",
    "rules.js",
    "suggest.js",
    "custom-dict.js",
    "backend.js",
    "ui.js",
    "index.js",
]

IMPORT_RE = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*[\"'][^\"']+[\"'];\s*$", re.MULTILINE)
EXPORT_RE = re.compile(r"^export\s*\{[^}]*\};\s*$", re.MULTILINE)
ALIAS_RE = re.compile(r"^\s*(\S+)\s+as\s+(\S+)\s*$")


class BundleError(Exception):
    """Raised when a source file doesn't match the expected import/export shape (PY-6)."""


def collect_aliases(text: str) -> list[str]:
    """Every module's functions/consts land in ONE flat scope once concatenated
    (function declarations hoist, so order doesn't matter here) — but an
    `import { x as y } from "./m.js"` renames `x` to `y` only in the importing
    file's own scope. Flattening drops that renaming, so `y` (e.g. index.js's
    `rulesCheck` for rules.js's `check`) is never defined -> ReferenceError at
    call time. Re-create each alias as a top-level `var y = x;` instead of
    silently dropping it."""
    aliases: list[str] = []
    for names in IMPORT_RE.findall(text):
        for entry in names.split(","):
            m = ALIAS_RE.match(entry)
            if m:
                aliases.append(f"var {m.group(2)} = {m.group(1)};")
    return aliases


def strip_module_syntax(text: str, name: str) -> str:
    stripped = IMPORT_RE.sub("", text)
    stripped = EXPORT_RE.sub("", stripped)
    if "import " in stripped or re.search(r"^export\b", stripped, re.MULTILINE):
        raise BundleError(
            f"{name}: import/export syntax survived stripping — bundler regex didn't match "
            f"this file's actual shape; fix the bundler, don't ship broken output"
        )
    return stripped


def bundle() -> str:
    parts: list[str] = [
        "/* AUTO-GENERATED by build/bundle_spelling.py — do not edit by hand.\n"
        "   Source of truth is _modules/Spelling/src/*.js; rerun the bundler\n"
        "   after any source edit. Concatenated in dependency order, module\n"
        "   syntax stripped, wrapped in one IIFE exposing window.createSpellingModule\n"
        "   and window.SpellingBackend. */",
        "(function (global) {",
        '"use strict";',
    ]
    missing = [name for name in ORDER if not (SRC_DIR / name).exists()]
    if missing:
        raise BundleError(f"expected source file(s) not found in {SRC_DIR}: {missing}")

    aliases: list[str] = []
    for name in ORDER:
        path = SRC_DIR / name
        raw = path.read_text(encoding="utf-8")
        aliases.extend(collect_aliases(raw))
        parts.append(f"\n/* ---- src/{name} ---- */\n")
        parts.append(strip_module_syntax(raw, name))

    if aliases:
        parts.append("\n/* ---- import aliases (flattened from per-file ES-module renames) ---- */\n")
        parts.append("\n".join(aliases))

    parts.append(
        "\nglobal.createSpellingModule = createSpellingModule;\n"
        "global.SpellingBackend = {\n"
        "  createBackend: createBackend,\n"
        "  createSqlJsBackend: createSqlJsBackend,\n"
        "  supportsGzipDecompression: supportsGzipDecompression,\n"
        "  decompressGzipBase64: decompressGzipBase64\n"
        "};\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n"
    )
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    try:
        output = bundle()
    except BundleError as exc:
        raise SystemExit(f"bundle_spelling.py: {exc}") from exc

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")
    print(f"wrote {args.out}: {len(output):,} bytes")


if __name__ == "__main__":
    main()
